#!/usr/bin/env python3
"""Export exact certificate inputs; Lean, not this exporter, checks the identities.

`--check` requires byte-for-byte agreement with every generated Lean source.
No residuals, verdicts, or Python-produced proofs are exported. Raw pattern
counts and tensor coefficients remain inputs to the Lean checker.
"""
from __future__ import annotations

import argparse
from fractions import Fraction
import hashlib
import json
import math
from pathlib import Path
import sys

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
from verification_json import exact_fraction, load_proof_json

BLOCKS = ('one_root', 'independent3', 'edge_isolate', 'path3', 'triangle3')
GENERATED = ROOT / 'formal/InducedPentagons/Generated'
HEADER = ('-- Generated by scripts/export_lean_certificate.py; do not edit.\n'
          '-- All arithmetic claims below must be checked by the Lean kernel.\n')
OPTIONS = 'set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n'


def integer(value):
    n = int(value)
    return str(n) if n >= 0 else '(' + str(n) + ')'


def array(values, multiline=False):
    values = list(values)
    return '#[' + (',\n  ' if multiline else ', ').join(values) + ']'


def vector(values):
    return array(map(integer, values))


def quote(value):
    return json.dumps(str(value), ensure_ascii=True)


def coefficient(value, scale, label=''):
    q = exact_fraction(value, label or 'Lean coefficient')
    w = q * scale
    assert w.denominator == 1
    return f'\u27e8{quote(label)}, {integer(q.numerator)}, {q.denominator}, {integer(w.numerator)}\u27e9'


def source(imports, body):
    return (HEADER + ''.join(f'import {name}\n' for name in imports) + '\n' + OPTIONS +
            'namespace InducedPentagons.Generated\n\n' + body +
            '\nend InducedPentagons.Generated\n').encode('utf-8')


def produce():
    input_names = [
        'certificates/all_graph_exact_certificate.json',
        'certificates/all_graph_path3_triangle_domination_span.json',
        'certificates/all_graph_tf_degree_codegree_spans.json',
        'certificates/flag_basis.npz', 'certificates/pattern_columns.npz',
    ]
    certificate, triangle, degree = [load_proof_json(ROOT / name) for name in input_names[:3]]
    assert certificate['schema'] == 'induced-pentagons.exact-certificate.v1'
    assert triangle['schema'] == 'induced-pentagons.triangle-span.v1'
    assert degree['schema'] == 'induced-pentagons.degree-codegree-spans.v1'
    digest = hashlib.sha256((ROOT / input_names[0]).read_bytes()).hexdigest()
    assert triangle['certificate_sha256'] == degree['certificate_sha256'] == digest
    with np.load(ROOT / input_names[3], allow_pickle=False) as f:
        flags = {key: f[key] for key in f.files}
    with np.load(ROOT / input_names[4], allow_pickle=False) as f:
        patterns = {key: f[key] for key in f.files}
    assert certificate['host_masks'] == flags['host_masks'].tolist() == patterns['host_masks'].tolist()
    assert len(certificate['host_masks']) == 1044
    assert [r['name'] for r in certificate['free_columns']] == patterns['free_names'].tolist()
    assert [r['name'] for r in certificate['positive_columns']] == patterns['positive_names'].tolist()
    assert certificate['constants'] == {'pstar': '5/144', 'tau': '5/663552'}
    expected_patterns = ['p', 'theta', 'L1', 'L2', 'L3', 'B1', 'B2', 'B3',
                         'L_triangle', 'B_triangle', 'R0', 'J0_A', 'J0_B', 'R1',
                         'J1_A', 'J1_B', 'Jdel_Lg', 'Jdel_Lf00', 'Jdel_Lf01',
                         'Jdel_Lf10', 'Jdel_Lf11', 'Ddel']
    assert patterns['pattern_names'].tolist() == expected_patterns
    fractions = [exact_fraction(r['coefficient'], category) for category in
                 ('free_columns', 'positive_columns', 'squares', 'slacks') for r in certificate[category]]
    scale = math.lcm(*(q.denominator for q in fractions))
    pieces = {}
    def emit(name, imports, body):
        pieces[name] = source(imports, body)

    free = array((coefficient(r['coefficient'], scale, r['name']) for r in certificate['free_columns']), True)
    positive = array((coefficient(r['coefficient'], scale, r['name']) for r in certificate['positive_columns']), True)
    slacks = array((coefficient(r['coefficient'], scale, str(r['host_mask'])) for r in certificate['slacks']), True)
    squares = []
    for r in certificate['squares']:
        b = BLOCKS.index(r['block'])
        squares.append(f'\u27e8{quote(r["id"])}, {b}, ' +
                       coefficient(r['coefficient'], scale) + ', ' + vector(r['vector']) + '\u27e9')
    blocks = []
    for b in BLOCKS:
        masks = vector(flags['flag_masks_' + b])
        kernel = array((vector(row) for row in flags['Q_basis_' + b]), True)
        blocks.append(f'\u27e8{masks}, {int(flags["denominator_" + b])}, {kernel}\u27e9')
    emit('Inputs.lean', ['InducedPentagons.Verifier'],
         'def certificate : Certificate := {\n' +
         f'  scale := {scale}\n  dataDenominator := 557383680\n' +
         '  hosts := ' + vector(certificate['host_masks']) + '\n' +
         '  fixedMasks := ' + vector(patterns['fixed_density_graph_masks']) + '\n' +
         '  patternDenominators := ' + vector(patterns['pattern_denominators']) + '\n' +
         '  free := ' + free + '\n  positive := ' + positive + '\n' +
         '  squares := ' + array(squares, True) + '\n' +
         '  slacks := ' + slacks + '\n  blocks := ' + array(blocks, True) + '\n}\n')
    emit('Metadata.lean', ['InducedPentagons.Generated.Inputs'],
         'theorem metadata_checked : checkMetadata certificate = true := by decide +kernel\n')

    grams = []
    for b, block in enumerate(BLOCKS):
        dim = len(flags['flag_masks_' + block])
        gram = np.zeros((dim, dim), dtype=object)
        for r in certificate['squares']:
            if r['block'] == block:
                weight = exact_fraction(r['coefficient'], r['id']) * scale
                assert weight.denominator == 1
                v = np.array(r['vector'], dtype=object)
                gram += weight.numerator * np.outer(v, v)
        rows = [[int(gram[i, j]) for j in range(i, dim)] for i in range(dim)]
        grams.append([x for row in rows for x in row])
        data_imports = ['InducedPentagons.Verifier']
        if b:
            data_imports.append(f'InducedPentagons.Generated.GramData{b - 1}')
        emit(f'GramData{b}.lean', data_imports,
             f'def gramBlock{b} : Array (Array Int) := ' + array((vector(row) for row in rows), True) + '\n')
    emit('GramData.lean', ['InducedPentagons.Generated.Inputs'] +
         [f'InducedPentagons.Generated.GramData{b}' for b in range(5)],
         'def gramData : GramData := #[gramBlock0, gramBlock1, gramBlock2, gramBlock3, gramBlock4]\n')
    gram_proofs = []
    for b, block in enumerate(BLOCKS):
        proofs = []
        for i in range(len(flags['flag_masks_' + block])):
            name = f'gram_{b}_{i}_checked'
            proofs.append(f'theorem {name} : checkGramRowFast certificate gramData {b} {i} = true := by decide +kernel\n')
            gram_proofs.append((name, f'checkGramRowFast certificate gramData {b} {i}'))
        gram_imports = ['InducedPentagons.Generated.GramData', 'InducedPentagons.FastVerifier']
        if b:
            gram_imports.append(f'InducedPentagons.Generated.GramProofs{b - 1}')
        emit(f'GramProofs{b}.lean', gram_imports, '\n'.join(proofs))

    host_proofs = []
    host_chunks = (1044 + 11) // 12
    for chunk in range(host_chunks):
        rows = []
        for h in range(chunk * 12, min(1044, (chunk + 1) * 12)):
            tensor = []
            for b, block in enumerate(BLOCKS):
                mat = flags['C_' + block][h]
                assert np.all(mat >= 0)
                for i in range(mat.shape[0]):
                    for j in range(i, mat.shape[1]):
                        count = int(mat[i, j]) + (int(mat[j, i]) if i != j else 0)
                        if count:
                            tensor.append(f'\u27e8{b}, {i}, {j}, {count}\u27e9')
            rows.append(f'\u27e8{h}, {certificate["host_masks"][h]}, ' +
                        vector(patterns['pattern_counts'][h]) + ', ' +
                        vector(patterns['fixed_density_induced_counts'][h]) + ', ' +
                        vector(patterns['fixed_density_complement_edge_counts'][h]) + ', ' +
                        array(tensor, True) + '\u27e9')
        name = f'hosts_{chunk:03d}_checked'
        expr = f'checkHostChunk certificate gramData {chunk * 12} hostChunk{chunk:03d}'
        # A chain of batches bounds simultaneous kernel jobs and peak memory.
        host_imports = ['InducedPentagons.Generated.GramData',
                        f'InducedPentagons.Generated.Hosts{chunk - 1:03d}' if chunk else
                        'InducedPentagons.Generated.GramProofs4']
        emit(f'Hosts{chunk:03d}.lean', host_imports,
             f'def hostChunk{chunk:03d} : Array HostRow := ' + array(rows, True) + '\n\n' +
             f'theorem {name} : {expr} = true := by decide +kernel\n')
        host_proofs.append((name, expr))

    indices = {r['id']: i for i, r in enumerate(certificate['squares'])}
    assert len(indices) == 184
    assert triangle['flag_masks'] == flags['flag_masks_path3'].tolist()
    witness_items = [(0, list(range(72)), triangle['combination'], triangle['result_vector']),
                     (1, degree['degree']['flag_indices'], degree['degree']['combination'], [])]
    codegree = sorted(degree['codegree'], key=lambda item: item['root'])
    assert [r['root'] for r in codegree] == [0, 1]
    for item in codegree:
        witness_items.append((item['root'] + 2, item['flag_indices'], item['combination'], []))
    spans = []
    for kind, ix, combination, target in witness_items:
        values = [exact_fraction(r['coefficient'], 'span') for r in combination] + [Fraction(x) for x in target]
        den = math.lcm(*(q.denominator for q in values))
        terms = []
        for term in combination:
            name = term['source_id']
            extra = int(name[-1]) + 1 if name in ('degree_identity_0', 'degree_identity_1') else 0
            source_index = 0 if extra else indices[name]
            terms.append(f'\u27e8{source_index}, {quote(name)}, {extra}, ' +
                         coefficient(term['coefficient'], den) + '\u27e9')
        target_vector = array((coefficient(x, den) for x in target), True)
        spans.append(f'\u27e8{kind}, {den}, {vector(ix)}, ' + array(terms, True) + ', ' + target_vector + '\u27e9')
    body = '\n'.join(f'def span{i} : SpanWitness := {value}\n' for i, value in enumerate(spans))
    body += '\n' + '\n'.join(f'theorem span_{i}_checked : checkSpan certificate span{i} = true := by decide +kernel\n'
                              for i in range(4))
    emit('Spans.lean', ['InducedPentagons.Generated.Inputs'], body)

    all_proofs = [('metadata_checked', 'checkMetadata certificate')] + gram_proofs + host_proofs + [
        (f'span_{i}_checked', f'checkSpan certificate span{i}') for i in range(4)]
    imported = ['InducedPentagons.Generated.Metadata', 'InducedPentagons.Generated.Spans'] + [
        f'InducedPentagons.Generated.GramProofs{b}' for b in range(5)] + [
        f'InducedPentagons.Generated.Hosts{k:03d}' for k in range(host_chunks)]
    body = '/-- Every actual finite certificate check, including every Gram row and host. -/\n'
    body += 'def coreCertificateChecks : Bool :=\n  ' + ' &&\n  '.join(expr for _, expr in all_proofs) + '\n\n'
    body += 'theorem coreCertificateVerified : coreCertificateChecks = true := by\n'
    body += '  simp only [coreCertificateChecks,\n    ' + ',\n    '.join(name for name, _ in all_proofs) + ',\n    Bool.true_and]\n'
    emit('Complete.lean', imported, body)
    def adjacent(a, b):
        return (a ^ b) in (1, 2, 4, 8, 15)
    neighborhoods = [[b for b in range(16) if adjacent(a, b)] for a in range(16)]
    pentagons = []
    for a in range(16):
        for b in neighborhoods[a]:
            for c in neighborhoods[b]:
                for d in neighborhoods[c]:
                    for e in neighborhoods[d]:
                        p = (a, b, c, d, e)
                        if not (a < min(b, c, d, e) and b < e):
                            continue
                        if all(adjacent(p[i], p[j]) == (((i + 1) % 5 == j) or ((j + 1) % 5 == i))
                               for i in range(5) for j in range(5)):
                            pentagons.append(p)
    assert len(pentagons) == len(set(pentagons)) == 192
    emit('ClebschData.lean', ['InducedPentagons.FiniteGraph'],
         'def clebschPentagonData : List (PentagonTuple 16) :=\n  [' +
         ',\n  '.join('\u27e8' + ', '.join(map(str, p)) + '\u27e9' for p in pentagons) + ']\n')
    manifest = {
        'schema': 'induced-pentagons.lean-export.v1',
        'lean_toolchain': 'leanprover/lean4:v4.35.0',
        'scope': 'Finite SOS arithmetic and equality-span witnesses on imported exact tensors, not a full manuscript formalization.',
        'inputs': {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest() for name in input_names},
        'counts': {'hosts': 1044, 'positive_squares': 184, 'positive_slacks': 826,
                   'gram_entries': sum(map(len, grams)), 'gram_rows': len(gram_proofs),
                   'host_chunks': host_chunks, 'span_witnesses': 4,
                   'rational_scale_digits': len(str(scale)),
                   'clebsch_candidate_pentagons': len(pentagons)},
        'data_denominator': 557383680,
        'generated': {name: hashlib.sha256(data).hexdigest() for name, data in sorted(pieces.items())},
    }
    pieces['manifest.json'] = (json.dumps(manifest, indent=2) + '\n').encode('utf-8')
    return pieces, manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    pieces, manifest = produce()
    changed = []
    for name, data in pieces.items():
        path = GENERATED / name
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                changed.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if args.check and GENERATED.exists():
        changed.extend(str(p.relative_to(ROOT)) for p in GENERATED.glob('*.lean') if p.name not in pieces)
    if changed:
        raise SystemExit('Stale Lean exports: ' + ', '.join(changed))
    print(json.dumps({'status': 'current' if args.check else 'exported',
                      'files': len(pieces), 'bytes': sum(map(len, pieces.values())),
                      'counts': manifest['counts']}, indent=2))


if __name__ == '__main__':
    if hasattr(sys, 'set_int_max_str_digits'):
        sys.set_int_max_str_digits(0)
    main()
